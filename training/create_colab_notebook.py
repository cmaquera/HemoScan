                "    paths = [os.path.join(DATASET_ROOT, r['image_path']) for r in recs]\n",
                "    labels_anemia = [float(r['is_anemic']) for r in recs]\n",
                "    labels_hb = [float(r['hb_level']) for r in recs]\n",
                "    def _load(p, a, h):\n",
                "        img = tf.io.decode_image(tf.io.read_file(p), channels=3, expand_animations=False)\n",
